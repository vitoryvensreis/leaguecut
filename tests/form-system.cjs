'use strict';
// Pure helpers of public/assets/form-system.js must match app/input-validation.php.
const assert = require('node:assert/strict');
const f = require('../public/assets/form-system.js');
assert.ok(f.cpfValid('529.982.247-25') && !f.cpfValid('111.111.111-11') && !f.cpfValid('529.982.247-24'));
assert.ok(f.cnpjValid('11.222.333/0001-81') && !f.cnpjValid('11.222.333/0001-80'));
assert.equal(f.phoneNormalize('(85) 99216-2766'), '85992162766');
assert.equal(f.phoneNormalize('5585921627669'), '85921627669');
assert.equal(f.phoneNormalize('(20) 99999-9999'), null);
assert.equal(f.phoneNormalize('(85) 3222-1234', true), null);
assert.equal(f.phoneNormalize('(85) 3222-1234', false), '8532221234');
assert.equal(f.emailSuggestion('joao@gmial.com'), 'joao@gmail.com');
assert.equal(f.emailSuggestion('joao@hotmal.com'), 'joao@hotmail.com');
assert.equal(f.emailSuggestion('joao@gmail.com'), null);
assert.equal(f.emailSuggestion('joao@empresa.com.br'), null);
assert.equal(f.instagramNormalize('https://www.instagram.com/LeagueCut/'), 'leaguecut');
assert.equal(f.instagramNormalize('@@Perfil'), 'perfil');
assert.equal(f.httpsNormalize('meusite.com'), 'https://meusite.com');
assert.equal(f.pixDetect('fin@example.com'), 'EMAIL');
assert.equal(f.pixDetect('11222333000181'), 'CNPJ');
assert.equal(f.pixDetect('529.982.247-25'), 'CPF');
assert.equal(f.pixDetect('(85) 99216-2766'), 'PHONE');
assert.equal(f.pixError('CPF', '111.111.111-11') !== '', true);
assert.equal(f.pixError('PHONE', '(85) 99216-2766'), '');
assert.equal(f.pixError('', 'x'), 'Escolha o tipo da chave Pix.');
assert.equal(f.passwordScore('123456789012'), 1);
assert.ok(f.passwordScore('Arena-Clipes-2026!') >= 4);
assert.equal(f.formatCpf('52998224725'), '529.982.247-25');
assert.equal(f.formatCnpj('11222333000181'), '11.222.333/0001-81');
assert.equal(f.formatPhone('85992162766'), '(85) 99216-2766');
console.log('FORM_SYSTEM_OK');
