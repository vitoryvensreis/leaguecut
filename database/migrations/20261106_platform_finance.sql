CREATE TABLE IF NOT EXISTS platform_withdrawals (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  amount_cents BIGINT UNSIGNED NOT NULL,
  pix_key_type ENUM('CPF','CNPJ','EMAIL','PHONE','EVP') NOT NULL,
  pix_key_enc TEXT NOT NULL,
  pix_key_hint VARCHAR(80) NOT NULL,
  description VARCHAR(140) NULL,
  status ENUM('awaiting_authorization','authorized','sending','processing','paid','failed','refused','cancelled','expired','unknown') NOT NULL DEFAULT 'awaiting_authorization',
  requested_by BIGINT UNSIGNED NOT NULL,
  authorized_by BIGINT UNSIGNED NULL,
  authorized_at DATETIME NULL,
  link_token_hash CHAR(64) NULL,
  link_expires_at DATETIME NULL,
  link_sends TINYINT UNSIGNED NOT NULL DEFAULT 0,
  link_last_sent_at DATETIME NULL,
  provider_reference VARCHAR(60) NOT NULL UNIQUE,
  provider_transfer_id VARCHAR(90) NULL UNIQUE,
  provider_status VARCHAR(40) NULL,
  receipt_url VARCHAR(500) NULL,
  last_error VARCHAR(255) NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  completed_at DATETIME NULL,
  INDEX idx_platform_withdrawals_status (status, created_at),
  CONSTRAINT fk_pw_requested_by FOREIGN KEY (requested_by) REFERENCES users(id),
  CONSTRAINT fk_pw_authorized_by FOREIGN KEY (authorized_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS platform_finance_events (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  withdrawal_id BIGINT UNSIGNED NULL,
  event VARCHAR(60) NOT NULL,
  actor_user_id BIGINT UNSIGNED NULL,
  amount_cents BIGINT UNSIGNED NULL,
  status_from VARCHAR(40) NULL,
  status_to VARCHAR(40) NULL,
  detail VARCHAR(255) NOT NULL DEFAULT '',
  ip_hash CHAR(64) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  INDEX idx_pf_events_withdrawal (withdrawal_id, id),
  INDEX idx_pf_events_created (created_at),
  CONSTRAINT fk_pf_events_withdrawal FOREIGN KEY (withdrawal_id) REFERENCES platform_withdrawals(id) ON DELETE RESTRICT,
  CONSTRAINT fk_pf_events_actor FOREIGN KEY (actor_user_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
